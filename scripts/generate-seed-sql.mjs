// Generates supabase/seed.sql from src/lib/data/demo-seed.ts so the demo store
// and the Supabase seed always contain the same SAMPLE content.
// Usage: npm run db:seed-sql   (needs Node 22.18+ for TypeScript type stripping)
import { writeFileSync } from "node:fs";
import path from "node:path";
import {
  seedBranches,
  seedCategories,
  seedGallery,
  seedHeroSlides,
  seedMenuItems,
  seedSettings,
} from "../src/lib/data/demo-seed.ts";

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

const rows = (table, cols, items, fmt) =>
  `insert into public.${table} (${cols.join(", ")}) values\n` +
  items.map((it) => `  (${fmt(it).join(", ")})`).join(",\n") +
  `\non conflict (id) do nothing;\n`;

let sql = `-- GENERATED by scripts/generate-seed-sql.mjs. Do not edit by hand.\n-- SAMPLE CONTENT: replace through /admin before launch.\n\n`;

sql += rows(
  "branches",
  ["id", "name", "slug", "address", "area", "city", "phone", "email", "hours_note", "opening_hours", "directions_url", "google_review_url", "image_url", "is_active", "is_verified", "source_note", "display_order"],
  seedBranches,
  (b) => [q(b.id), q(b.name), q(b.slug), q(b.address), q(b.area), q(b.city), q(b.phone), q(b.email), q(b.hours_note), json(b.opening_hours), q(b.directions_url), q(b.google_review_url), q(b.image_url), q(b.is_active), q(b.is_verified), q(b.source_note), q(b.display_order)],
) + "\n";

sql += rows(
  "menu_categories",
  ["id", "name", "slug", "description", "display_order", "is_active"],
  seedCategories,
  (c) => [q(c.id), q(c.name), q(c.slug), q(c.description), q(c.display_order), q(c.is_active)],
) + "\n";

sql += rows(
  "menu_items",
  ["id", "category_id", "name", "slug", "short_description", "description", "price", "image_url", "image_alt", "ingredients", "allergens", "allergens_verified", "dietary_labels", "is_available", "is_featured", "is_sample", "display_order"],
  seedMenuItems,
  (m) => [q(m.id), q(m.category_id), q(m.name), q(m.slug), q(m.short_description), q(m.description), q(m.price), q(m.image_url), q(m.image_alt), arr(m.ingredients), arr(m.allergens), q(m.allergens_verified), arr(m.dietary_labels), q(m.is_available), q(m.is_featured), q(m.is_sample), q(m.display_order)],
) + "\n";

sql += rows(
  "hero_slides",
  ["id", "image_url", "image_alt", "heading", "subheading", "primary_label", "primary_href", "secondary_label", "secondary_href", "display_order", "is_active"],
  seedHeroSlides,
  (s) => [q(s.id), q(s.image_url), q(s.image_alt), q(s.heading), q(s.subheading), q(s.primary_label), q(s.primary_href), q(s.secondary_label), q(s.secondary_href), q(s.display_order), q(s.is_active)],
) + "\n";

sql += rows(
  "gallery_images",
  ["id", "image_url", "alt", "caption", "placement", "display_order", "is_active"],
  seedGallery,
  (g) => [q(g.id), q(g.image_url), q(g.alt), q(g.caption), q(g.placement), q(g.display_order), q(g.is_active)],
) + "\n";

sql +=
  `insert into public.site_settings (key, value) values\n` +
  Object.entries(seedSettings).map(([k, v]) => `  (${q(k)}, ${json(v)})`).join(",\n") +
  `\non conflict (key) do nothing;\n`;

const out = path.join(process.cwd(), "supabase", "seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
